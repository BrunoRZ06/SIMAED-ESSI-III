import type { QuestionBankSeedItem } from "./question-bank.data.js";

type Draft = {
  disciplineCode: "PORTUGUESE" | "MATHEMATICS";
  descriptorCode: string;
  statement: string;
  stimulusText?: string;
  choices: [string, string, string, string];
  correct: "A" | "B" | "C" | "D";
};

function buildSource(sourceCode: string, drafts: Draft[]): QuestionBankSeedItem[] {
  return drafts.map((draft, index) => ({
    sourceCode,
    number: index + 1,
    itemCode: `AUT-${sourceCode.slice(-3)}-${draft.disciplineCode === "PORTUGUESE" ? "LP" : "MT"}-${draft.descriptorCode}`,
    disciplineCode: draft.disciplineCode,
    descriptorCode: draft.descriptorCode,
    statement: draft.statement,
    ...(draft.stimulusText ? { stimulusText: draft.stimulusText } : {}),
    pdfPageNumber: null,
    correctAlternative: draft.correct,
    answerSource: "Gabarito sugerido para item autoral de prática; pendente de revisão pedagógica.",
    alternatives: draft.choices.map((text, choiceIndex) => ({
      label: "ABCD"[choiceIndex]!,
      text,
    })),
  }));
}

